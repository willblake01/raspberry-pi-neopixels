import type { Answers } from 'prompts';
import { EFFECTS } from '../constants/index.js';
import { Options } from '../types/index.js';

export const normalizeAnswers = (response: Answers<string>): Options => {
  const {
    command,
    leds,
    gamma,
    brightness,
    effect,
    shift,
    interval,
    red,
    green,
    blue,
    red2,
    green2,
    blue2,
    colorType,
    randomColorMode,
    colorChangeInterval,
    pixelState,
    useMotionDetection,
    motionColorType,
    motionRed,
    motionGreen,
    motionBlue,
  } = response;

  return {
    // Values
    command,
    leds,
    gamma,
    brightness,
    effect,
    shift,
    interval,
    red,
    green,
    blue,
    red2,
    green2,
    blue2,
    colorType,
    randomColorMode,
    colorChangeInterval,
    pixelState,
    useMotionDetection,
    motionColorType,
    motionRed,
    motionGreen,
    motionBlue,
    pomodoroWorkMinutes: response.pomodoroWorkMinutes,
    pomodoroShortBreakMinutes: response.pomodoroShortBreakMinutes,
    pomodoroLongBreakMinutes: response.pomodoroLongBreakMinutes,
    pomodoroRounds: response.pomodoroRounds,
    locationType: response.locationType,
    location: response.location,
    weatherAlerts: response.weatherAlerts === 1 ? 1 : 0,
    pixelSegments: response.pixelSegments ?? [],
    showMoon: response.showMoon,

    // Flags
    isOn: command === 1,
    isOff: command === 0,
    isSolid: effect === EFFECTS.SOLID,
    isCheckerboard: effect === EFFECTS.CHECKERBOARD,
    isChange: effect === EFFECTS.CHANGE,
    isBlink: effect === EFFECTS.BLINK,
    isBreathe: effect === EFFECTS.BREATHE,
    isGrowingBar: effect === EFFECTS.GROWING_BAR,
    isWheel: effect === EFFECTS.WHEEL,
    isWalkPixel: effect === EFFECTS.WALK_PIXEL,
    isShift: shift === 1,
    isCustomColorMode: colorType === 'custom',
    isRandomColorMode: colorType === 'random',
    isStaticRandomColorMode: randomColorMode === 'static',
    isChangeRandomColorMode: randomColorMode === 'change',
    isPixelOn: pixelState === 1,
    isEveryPixelColorChangeInterval: colorChangeInterval === 'everyPixel',
    isEveryLoopColorChangeInterval: colorChangeInterval === 'everyLoop',
    isMotionDetectionEnabled: useMotionDetection === 1,
    isMotionCustomColorMode:
      useMotionDetection === 1 && motionColorType === 'custom',
    isMotionRandomColorMode:
      useMotionDetection === 1 && motionColorType === 'random',
    isWeather: effect === EFFECTS.WEATHER,
    isWeatherAlertsEnabled: response.weatherAlerts === 1
  };
};
